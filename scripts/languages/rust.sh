#!/usr/bin/env bash
set -euo pipefail

root=${AOC_ROOT:-$(cd "$(dirname "$0")/../.." && pwd)}
manifest="$root/rust/Cargo.toml"
target=${CARGO_TARGET_DIR:-$root/rust/target}
[[ "$target" = /* ]] || target="$root/rust/$target"
export CARGO_TARGET_DIR="$target"

fail() { printf '%s\n' "$*" >&2; exit 1; }
year=${2:-}
day=${3:-}

check_year() {
    [[ "$year" =~ ^[0-9]{4}$ ]] && ((10#$year >= 2015)) || fail 'year must be four digits, at least 2015'
}
check_day() {
    [[ "$day" =~ ^[0-9]{1,2}$ ]] && ((10#$day >= 1 && 10#$day <= 25)) || fail 'day must be between 1 and 25'
    day=$((10#$day))
}
build_year() {
    [[ -f "$root/rust/years/y$year/Cargo.toml" ]] || fail "no Rust solutions registered for $year"
    cargo build --quiet --release --locked --offline --manifest-path "$manifest" --package "aoc-y$year"
}

case ${1:-} in
    doctor)
        command -v cargo >/dev/null || fail 'missing cargo: install Rust with rustup'
        command -v rustc >/dev/null || fail 'missing rustc: install Rust with rustup'
        cargo --version
        rustc --version
        ;;
    build)
        check_year
        build_year
        ;;
    run)
        check_year
        check_day
        part=${4:-}
        [[ "$part" = 1 || "$part" = 2 ]] || fail 'run requires part 1 or 2'
        executable="$target/release/aoc-y$year"
        [[ -x "$executable" ]] || fail "Rust year $year is not built; run the adapter build command first"
        exec "$executable" run "$day" "$part"
        ;;
    bench)
        check_year
        check_day
        exec "$target/release/aoc-y$year" bench "$day" "${4:?part required}" "${5:?iterations required}" "${6:?warmup required}"
        ;;
    expect)
        check_year
        check_day
        exec "$target/release/aoc-y$year" expect "$day" "${4:?part required}" "${5:?example index required}"
        ;;
    example)
        check_year
        check_day
        exec "$target/release/aoc-y$year" example "$day" "${4:?example index required}"
        ;;
    test)
        check_year
        check_day
        part=${4:-both}
        [[ "$part" = 1 || "$part" = 2 || "$part" = both ]] || fail 'test part must be 1, 2 or both'
        build_year
        exec "$target/release/aoc-y$year" test "$day" "$part"
        ;;
    new)
        check_year
        check_day
        year_dir="$root/rust/years/y$year"
        source_dir="$year_dir/src"
        printf -v padded_day '%02d' "$day"
        solution="$source_dir/d$padded_day.rs"
        [[ ! -e "$solution" ]] || fail "refusing to overwrite $solution"
        registry="$source_dir/main.rs"
        if [[ -e "$registry" ]] && ! head -n 1 "$registry" | grep -qxF '// Generated by the Rust adapter. Register days through `aoc new`.'; then
            fail "refusing to replace custom registry $registry; register the day manually"
        fi
        mkdir -p "$source_dir"
        if [[ ! -e "$year_dir/Cargo.toml" ]]; then
            cat > "$year_dir/Cargo.toml" <<EOF
[package]
name = "aoc-y$year"
version = "0.1.0"
edition = "2021"

[dependencies]
aoc = { path = "../../aoc" }
EOF
        fi
        cat > "$solution" <<EOF
pub struct Solver;
impl aoc::Solution for Solver {
    type Prepared<'a> = aoc::Lines<'a>;
    type Answer = u64;
    // Set PARTS to &[1], &[2], or &[1, 2] only as those parts are implemented.

    fn process(input: aoc::Input<'_>) -> Result<Self::Prepared<'_>, String> { Ok(input.lines()) }
    fn part1(_input: Self::Prepared<'_>) -> Result<u64, String> {
        todo!("$year day $day part 1")
    }
    fn part2(_input: Self::Prepared<'_>) -> Result<u64, String> {
        todo!("$year day $day part 2")
    }
}

// aoc::example!("example", "inline input", part1 = expected_answer)
pub const EXAMPLES: &[aoc::Example<u64>] = &[];
EOF
        temporary=$(mktemp "$source_dir/.main.XXXXXX")
        trap 'rm -f "$temporary"' EXIT
        {
            printf '%s\n' '// Generated by the Rust adapter. Register days through `aoc new`.' 'aoc::main! {'
            for source in "$source_dir"/d[0-9][0-9].rs; do
                module=${source##*/}
                module=${module%.rs}
                number=${module#d}
                if grep -q 'impl aoc::Solution for Solver' "$source"; then
                    printf '    %d => %s: Solver,\n' "$((10#$number))" "$module"
                else
                    printf '    %d => %s,\n' "$((10#$number))" "$module"
                fi
            done
            printf '}\n'
        } > "$temporary"
        mv "$temporary" "$registry"
        cargo generate-lockfile --offline --manifest-path "$manifest"
        printf 'Created %s\n' "$solution"
        ;;
    *) fail 'usage: rust.sh build YEAR | run YEAR DAY PART | test YEAR DAY [PART] | example YEAR DAY INDEX | new YEAR DAY | doctor' ;;
esac
