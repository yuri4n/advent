package scaffold

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"

	"github.com/yurianthedev/advent/internal/runner"
)

var yearPattern = regexp.MustCompile(`^y[0-9]{2}$`)
var dayPattern = regexp.MustCompile(`^d[0-9]{2}$`)

func New(root string, year, day int) (string, error) {
	if year < 2015 || year > 2099 || day < 1 || day > 25 {
		return "", fmt.Errorf("year must be 2015..2099 and day 1..25")
	}
	yearDir := filepath.Join(root, fmt.Sprintf("y%02d", year%100))
	if err := os.MkdirAll(yearDir, 0755); err != nil {
		return "", err
	}
	dir := filepath.Join(yearDir, fmt.Sprintf("d%02d", day))
	if err := os.Mkdir(dir, 0755); err != nil {
		return "", fmt.Errorf("refusing to overwrite an existing day: %w", err)
	}
	complete := false
	defer func() {
		if !complete {
			os.RemoveAll(dir)
		}
	}()
	solution := fmt.Sprintf("package d%02d\n\nfunc Part1(input string) int {\n\tpanic(\"TODO: implement part 1\")\n}\n\nfunc Part2(input string) int {\n\tpanic(\"TODO: implement part 2\")\n}\n", day)
	samples := fmt.Sprintf("package d%02d\n\nimport \"testing\"\n\n// Keep sample input as an inline string in this file.\nfunc TestSamples(t *testing.T) {\n\tt.Run(\"part1\", func(t *testing.T) {\n\t\tt.Fatal(\"no samples: add an inline input and expected Part1 answer\")\n\t})\n\tt.Run(\"part2\", func(t *testing.T) {\n\t\tt.Fatal(\"no samples: add an inline input and expected Part2 answer\")\n\t})\n}\n", day)
	for name, data := range map[string]string{"solution.go": solution, "sample_test.go": samples} {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(data), 0644); err != nil {
			return "", err
		}
	}
	if err := GenerateRegistry(root); err != nil {
		return "", err
	}
	complete = true
	return dir, nil
}

// GenerateRegistry discovers day packages; it only replaces the owned generated file.
func GenerateRegistry(root string) error {
	var keys []runner.Key
	years, err := os.ReadDir(root)
	if err != nil {
		return err
	}
	for _, yearDir := range years {
		if !yearDir.IsDir() || !yearPattern.MatchString(yearDir.Name()) {
			continue
		}
		year, _ := strconv.Atoi(yearDir.Name()[1:])
		days, err := os.ReadDir(filepath.Join(root, yearDir.Name()))
		if err != nil {
			return err
		}
		for _, dayDir := range days {
			if !dayDir.IsDir() || !dayPattern.MatchString(dayDir.Name()) {
				continue
			}
			if _, err := os.Stat(filepath.Join(root, yearDir.Name(), dayDir.Name(), "solution.go")); err != nil {
				continue
			}
			day, _ := strconv.Atoi(dayDir.Name()[1:])
			keys = append(keys, runner.Key{Year: 2000 + year, Day: day})
		}
	}
	sort.Slice(keys, func(i, j int) bool {
		return keys[i].Year < keys[j].Year || keys[i].Year == keys[j].Year && keys[i].Day < keys[j].Day
	})
	var source bytes.Buffer
	fmt.Fprintln(&source, "// Code generated by cmd/scaffold; DO NOT EDIT.\n\npackage main\n\nimport (\n\t\"github.com/yurianthedev/advent/internal/runner\"")
	for _, key := range keys {
		fmt.Fprintf(&source, "\ty%02dd%02d \"github.com/yurianthedev/advent/y%02d/d%02d\"\n", key.Year%100, key.Day, key.Year%100, key.Day)
	}
	fmt.Fprintln(&source, ")\n\nvar days = map[runner.Key]runner.Day{")
	for _, key := range keys {
		fmt.Fprintf(&source, "\t{Year: %d, Day: %d}: runner.Register(y%02dd%02d.Part1, y%02dd%02d.Part2),\n", key.Year, key.Day, key.Year%100, key.Day, key.Year%100, key.Day)
	}
	fmt.Fprintln(&source, "}")
	formatted, err := format.Source(source.Bytes())
	if err != nil {
		return err
	}
	path := filepath.Join(root, "cmd", "aoc", "days_gen.go")
	if existing, err := os.ReadFile(path); err == nil && !bytes.HasPrefix(existing, []byte("// Code generated by cmd/scaffold; DO NOT EDIT.")) {
		return fmt.Errorf("refusing to overwrite manually maintained %s", path)
	} else if err != nil && !os.IsNotExist(err) {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		return err
	}
	file, err := os.CreateTemp(filepath.Dir(path), ".registry-*.go")
	if err != nil {
		return err
	}
	defer os.Remove(file.Name())
	if _, err := file.Write(formatted); err != nil {
		file.Close()
		return err
	}
	if err := file.Close(); err != nil {
		return err
	}
	return os.Rename(file.Name(), path)
}
